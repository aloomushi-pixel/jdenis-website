-- =============================================================================
-- Migración Supabase / PostgreSQL: Catálogo Normalizado J. Denis v2 (jdenis.store)
-- Sustituye el esquema anterior (products + variant_groups + product_variants)
-- por public.products (215 padres) y public.product_variants (524 variantes).
-- =============================================================================

BEGIN;

-- 0. Eliminar tablas del catálogo anterior (respaldadas en supabase/backups/)
DROP TABLE IF EXISTS public.product_variants CASCADE;
DROP TABLE IF EXISTS public.variant_groups CASCADE;
DROP TABLE IF EXISTS public.products CASCADE;

-- 1. Función reutilizable para actualizar updated_at automáticamente
CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$;

-- 2. Tabla maestra de productos padre (public.products)
CREATE TABLE public.products (
  product_id            INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  slug                  TEXT NOT NULL UNIQUE,
  name                  TEXT NOT NULL,
  brand                 TEXT NOT NULL DEFAULT 'J. Denis',
  category              TEXT NOT NULL,
  raw_categories        TEXT,
  description           TEXT NOT NULL DEFAULT '',
  description_html      TEXT NOT NULL DEFAULT '',
  image_url             TEXT,
  gallery_images        JSONB NOT NULL DEFAULT '[]'::jsonb,
  has_variants          BOOLEAN NOT NULL DEFAULT FALSE,
  variant_attributes    TEXT,
  variants_count        INTEGER NOT NULL DEFAULT 1 CHECK (variants_count >= 1),
  base_price_mxn        NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (base_price_mxn >= 0),
  promo_price_mxn       NUMERIC(10, 2) CHECK (promo_price_mxn IS NULL OR promo_price_mxn >= 0),
  distributor_price_mxn NUMERIC(10, 2) CHECK (distributor_price_mxn IS NULL OR distributor_price_mxn >= 0),
  promotion_label       TEXT,
  total_stock           INTEGER NOT NULL DEFAULT 0 CHECK (total_stock >= 0),
  is_active             BOOLEAN NOT NULL DEFAULT TRUE,
  is_featured           BOOLEAN NOT NULL DEFAULT FALSE,
  sort_order            INTEGER NOT NULL DEFAULT 0,
  free_shipping         BOOLEAN NOT NULL DEFAULT FALSE,
  tags                  TEXT,
  seo_title             TEXT,
  seo_description       TEXT,
  benefits              JSONB NOT NULL DEFAULT '[]'::jsonb,
  includes              JSONB NOT NULL DEFAULT '[]'::jsonb,
  performance           TEXT,
  specifications        JSONB NOT NULL DEFAULT '[]'::jsonb,
  video                 TEXT,
  related_categories    JSONB NOT NULL DEFAULT '[]'::jsonb,
  jdenis_store_status   TEXT,
  source_url            TEXT,
  audit_notes           TEXT,
  created_at            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at            TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. Tabla hija de variantes por producto (public.product_variants)
CREATE TABLE public.product_variants (
  variant_id               INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  product_id               INTEGER NOT NULL REFERENCES public.products(product_id) ON DELETE CASCADE,
  product_slug             TEXT NOT NULL REFERENCES public.products(slug) ON UPDATE CASCADE ON DELETE CASCADE,
  original_tiendanube_slug TEXT NOT NULL DEFAULT '',
  sku                      TEXT,
  barcode                  TEXT,
  variant_title            TEXT NOT NULL,
  option_1_name            TEXT,
  option_1_value           TEXT,
  option_2_name            TEXT,
  option_2_value           TEXT,
  option_3_name            TEXT,
  option_3_value           TEXT,
  price_mxn                NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (price_mxn >= 0),
  promo_price_mxn          NUMERIC(10, 2) CHECK (promo_price_mxn IS NULL OR (promo_price_mxn > 0 AND promo_price_mxn < price_mxn)),
  cost_mxn                 NUMERIC(10, 2) CHECK (cost_mxn IS NULL OR cost_mxn >= 0),
  stock                    INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
  weight_kg                NUMERIC(8, 3) NOT NULL DEFAULT 0,
  height_cm                NUMERIC(8, 2) NOT NULL DEFAULT 0,
  width_cm                 NUMERIC(8, 2) NOT NULL DEFAULT 0,
  depth_cm                 NUMERIC(8, 2) NOT NULL DEFAULT 0,
  image_url                TEXT,
  variant_description      TEXT,
  is_active                BOOLEAN NOT NULL DEFAULT TRUE,
  source_url               TEXT,
  created_at               TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at               TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. Índices para consultas rápidas en tienda, filtros y buscador
CREATE INDEX idx_products_category_active ON public.products (category, is_active);
CREATE INDEX idx_products_is_active ON public.products (is_active);
CREATE INDEX idx_products_featured ON public.products (is_featured) WHERE is_active = TRUE;
CREATE INDEX idx_product_variants_product_id ON public.product_variants (product_id);
CREATE INDEX idx_product_variants_product_slug ON public.product_variants (product_slug);
CREATE INDEX idx_product_variants_sku ON public.product_variants (sku) WHERE sku IS NOT NULL;
CREATE INDEX idx_product_variants_active_stock ON public.product_variants (product_id, is_active, stock);

-- 5. Triggers updated_at
CREATE TRIGGER trg_products_updated_at
  BEFORE UPDATE ON public.products
  FOR EACH ROW
  EXECUTE FUNCTION public.set_updated_at();

CREATE TRIGGER trg_product_variants_updated_at
  BEFORE UPDATE ON public.product_variants
  FOR EACH ROW
  EXECUTE FUNCTION public.set_updated_at();

-- 6. Función auxiliar para sincronizar secuencias IDENTITY tras importar IDs explícitos
CREATE OR REPLACE FUNCTION public.sync_catalog_sequences()
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  PERFORM setval(
    pg_get_serial_sequence('public.products', 'product_id'),
    COALESCE((SELECT MAX(product_id) FROM public.products), 1),
    TRUE
  );
  PERFORM setval(
    pg_get_serial_sequence('public.product_variants', 'variant_id'),
    COALESCE((SELECT MAX(variant_id) FROM public.product_variants), 1),
    TRUE
  );
END;
$$;

-- 7. Función auxiliar para determinar si el usuario autenticado es personal administrativo
CREATE OR REPLACE FUNCTION public.is_catalog_staff()
RETURNS BOOLEAN
LANGUAGE sql
SECURITY DEFINER
STABLE
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.users u
    WHERE u.id = auth.uid()::text
      AND u.role::text IN ('ADMIN', 'EJECUTIVO', 'ALMACEN_PRODUCTO_FINAL')
      AND COALESCE(u.is_active, TRUE) = TRUE
  );
$$;

-- 8. Row Level Security (RLS) para Supabase
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.product_variants ENABLE ROW LEVEL SECURITY;

-- Lectura pública en jdenis.store para productos/variantes activos
CREATE POLICY "Lectura pública de productos activos"
  ON public.products
  FOR SELECT
  TO anon, authenticated
  USING (is_active = TRUE OR public.is_catalog_staff());

CREATE POLICY "Lectura pública de variantes activas"
  ON public.product_variants
  FOR SELECT
  TO anon, authenticated
  USING (is_active = TRUE OR public.is_catalog_staff());

-- Gestión desde el panel Admin web para personal autorizado
CREATE POLICY "Gestión staff en products"
  ON public.products
  FOR ALL
  TO authenticated
  USING (public.is_catalog_staff())
  WITH CHECK (public.is_catalog_staff());

CREATE POLICY "Gestión staff en product_variants"
  ON public.product_variants
  FOR ALL
  TO authenticated
  USING (public.is_catalog_staff())
  WITH CHECK (public.is_catalog_staff());

-- Acceso total de administración mediante service_role (backend / scripts de importación)
CREATE POLICY "Administración total service_role en products"
  ON public.products
  FOR ALL
  TO service_role
  USING (TRUE)
  WITH CHECK (TRUE);

CREATE POLICY "Administración total service_role en product_variants"
  ON public.product_variants
  FOR ALL
  TO service_role
  USING (TRUE)
  WITH CHECK (TRUE);

COMMIT;
